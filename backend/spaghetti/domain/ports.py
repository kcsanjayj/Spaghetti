"""Ports = the contracts the inner layers rely on (dependency inversion)."""
from typing import Protocol


class ChatModel(Protocol):
    def chat(self, messages: list[dict], model: str) -> str: ...


class Engine(Protocol):
    name: str

    def chunk(self, text: str, size: int, overlap: int) -> list[str]: ...
    def rank(self, query: str, chunks: list[str], k: int) -> list[tuple[int, float]]: ...
    def overlap(self, answer: str, context: str) -> float: ...
    def hardware(self) -> dict: ...
